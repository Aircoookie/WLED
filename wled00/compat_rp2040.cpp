String wledBSSIDstr(int16_t networkItem) {
  uint8_t bssid[6] = {0,0,0,0,0,0};
  if (networkItem < 0) WiFi.BSSID(bssid);
  else                  WiFi.BSSID((uint8_t)networkItem, bssid);
  char buf[18];
  snprintf(buf, sizeof(buf), MACSTR, MAC2STR(bssid));
  return String(buf);
}


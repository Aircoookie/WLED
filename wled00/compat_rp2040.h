// Hang/crash safety net + post-mortem diagnostics. WLED_WATCHDOG_TIMEOUT is 0 (off) by default,
// and on this platform a lockup (hard fault, or a deadlock in the main loop or an IRQ handler)
// leaves the board dead - USB-CDC included - until it is power-cycled.
// - The RP2040 hardware watchdog is armed, but fed from a 1s repeating timer IRQ rather than
//   directly from loop(): CYW43's synchronous WiFi join legitimately blocks loop() for up to
//   ~15s, longer than the watchdog's ~8.3s hardware maximum. The timer only feeds while loop()
//   has checked in within RP2040_LOOP_STALL_MS, so a stuck loop() still ends in a reset.
// - The current loop() phase ("breadcrumb") lives in watchdog scratch register 0, which
//   survives a watchdog reset (scratch 4-7 are reserved by the bootrom, 0-3 are free).
// - A HardFault handler saves the faulting PC/LR to scratch 2/3 and reboots immediately.
// After the reboot, wledResetReason() describes what happened (serial debug dump + /json/info).
enum WledCrumb : uint8_t {
  CRUMB_NONE = 0, CRUMB_SETUP, CRUMB_TIME, CRUMB_CONNECTION, CRUMB_NOTIFICATIONS, CRUMB_TRANSITIONS,
  CRUMB_USERMODS, CRUMB_IO, CRUMB_DNS, CRUMB_PRESETS, CRUMB_STRIP, CRUMB_HOUSEKEEPING,
  CRUMB_CFGWRITE, CRUMB_WS, CRUMB_LOOPEND
};
void wledCrumb(WledCrumb c);   // record the loop() phase about to run
void wledWatchdogBegin();      // call once at the end of setup()
void wledWatchdogLoopBeat();   // call once per loop() iteration
const char* wledResetReason(); // human-readable cause of the previous reset
